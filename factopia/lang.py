def _lang() -> str:
    """当前请求的地区（hq/hk/uk/fr）；导入失败或无上下文（runner 子进程、脚本）回退 hq。"""
    try:
        from factopia import access
        cur = access._current.get()
    except Exception:
        cur = None
    return cur if cur in _DICTS else "hq"


def t(key: str, **vars) -> str:
    """按当前地区语言输出文案；键为简体中文原文，未收录回退简体。"""
    s = _DICTS[_lang()].get(key, key)
    for name, value in vars.items():
        s = s.replace("{" + name + "}", str(value))
    return s


def llm_language() -> str:
    """提示词模板 {language} 参数：要求大模型输出的语言。"""
    return LLM_LANGUAGE[_lang()]


def market_label(market: str) -> str:
    return MARKET_LABELS[_lang()].get(market, market)


def role_label(code: str, fallback: str = "") -> str:
    return ROLE_LABELS[_lang()].get(code) or fallback


def joinlist(items) -> str:
    """列表按语言拼接（中文顿号 / 西文逗号加空格）。"""
